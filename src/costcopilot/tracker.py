"""Regenerate the project plan, skills matrix and activity log.

`docs/project-plan/plan.json` is the single source of truth. Run `update-tracker` after
changing task statuses; the git activity log is derived from commit history.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from collections import defaultdict
from pathlib import Path

ICONS = {"done": "✅ Done", "in_progress": "🔄 In progress", "planned": "⏳ Planned"}
VALID_STATUS = set(ICONS)


def load_plan(path: Path) -> dict:
    plan = json.loads(path.read_text(encoding="utf-8"))
    validate(plan)
    return plan


def validate(plan: dict) -> None:
    catalog = plan["skill_catalog"]
    seen: set[str] = set()
    for phase in plan["phases"]:
        for task in phase["tasks"]:
            if task["id"] in seen:
                raise ValueError(f"duplicate task id {task['id']}")
            seen.add(task["id"])
            if task["status"] not in VALID_STATUS:
                raise ValueError(f"task {task['id']}: invalid status {task['status']!r}")
            unknown = [s for s in task["skills"] if s not in catalog]
            if unknown:
                raise ValueError(f"task {task['id']}: skills not in catalog: {unknown}")


def _tasks(plan: dict):
    for phase in plan["phases"]:
        yield from phase["tasks"]


def progress(plan: dict) -> tuple[int, int]:
    tasks = list(_tasks(plan))
    return sum(t["status"] == "done" for t in tasks), len(tasks)


def render_plan(plan: dict) -> str:
    done, total = progress(plan)
    pct = round(100 * done / total) if total else 0
    lines = [
        f"# {plan['project']}: project plan",
        "",
        "_Generated by `update-tracker` from `plan.json`. Do not edit by hand._",
        "",
        f"**Overall progress: {done}/{total} tasks ({pct}%)**",
        "",
        "| Phase | Done | Status |",
        "|---|---|---|",
    ]
    for phase in plan["phases"]:
        tasks = phase["tasks"]
        d = sum(t["status"] == "done" for t in tasks)
        state = "✅" if d == len(tasks) else "🔄" if d or any(
            t["status"] == "in_progress" for t in tasks) else "⏳"
        lines.append(f"| {phase['id']}. {phase['name']} | {d}/{len(tasks)} | {state} |")
    for phase in plan["phases"]:
        lines += ["", f"## Phase {phase['id']}: {phase['name']}", "",
                  "| ID | Task | Status | Skills | Evidence |", "|---|---|---|---|---|"]
        for t in phase["tasks"]:
            ev = f"`{t['evidence']}`" if t.get("evidence") else ""
            lines.append(
                f"| {t['id']} | {t['title']} | {ICONS[t['status']]} | "
                f"{', '.join(t['skills'])} | {ev} |"
            )
    return "\n".join(lines) + "\n"


def render_skills(plan: dict) -> str:
    catalog = plan["skill_catalog"]
    stats: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for t in _tasks(plan):
        for skill in t["skills"]:
            stats[skill][1] += 1
            stats[skill][0] += t["status"] == "done"
    by_cat: dict[str, list[str]] = defaultdict(list)
    for skill, cat in catalog.items():
        by_cat[cat].append(skill)
    lines = [
        "# Skills matrix",
        "",
        "_Generated by `update-tracker`. Demonstrated = completed tasks using the skill._",
        "",
    ]
    for cat in sorted(by_cat):
        lines += [f"## {cat}", "", "| Skill | Demonstrated | Planned |", "|---|---|---|"]
        for skill in sorted(by_cat[cat]):
            d, n = stats.get(skill, [0, 0])
            lines.append(f"| {skill} | {d} | {n - d} |")
        lines.append("")
    return "\n".join(lines)


def git_commits(repo: Path) -> list[dict]:
    fmt = "%h\x1f%ad\x1f%an\x1f%s"
    try:
        out = subprocess.run(
            ["git", "log", f"--pretty=format:{fmt}", "--date=short", "--shortstat"],
            cwd=repo, capture_output=True, text=True, check=True,
        ).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        return []
    commits: list[dict] = []
    for raw in out.splitlines():
        if "\x1f" in raw:
            h, date, author, subject = raw.split("\x1f", 3)
            commits.append({"hash": h, "date": date, "author": author,
                            "subject": subject, "stat": ""})
        elif raw.strip() and commits:
            commits[-1]["stat"] = raw.strip()
    return commits


def render_activity(commits: list[dict]) -> str:
    lines = [
        "# Activity log",
        "",
        "_Generated by `update-tracker` from git history, newest first._",
        "",
    ]
    if not commits:
        return "\n".join(lines + ["No commits yet."]) + "\n"
    lines += ["| Date | Commit | Change | Size |", "|---|---|---|---|"]
    for c in commits:
        lines.append(f"| {c['date']} | `{c['hash']}` | {c['subject']} | {c['stat']} |")
    return "\n".join(lines) + "\n"


def build(root: Path) -> list[Path]:
    folder = root / "docs" / "project-plan"
    plan = load_plan(folder / "plan.json")
    outputs = {
        "PLAN.md": render_plan(plan),
        "SKILLS.md": render_skills(plan),
        "ACTIVITY_LOG.md": render_activity(git_commits(root)),
    }
    written = []
    for name, text in outputs.items():
        target = folder / name
        target.write_text(text, encoding="utf-8", newline="\n")
        written.append(target)
    return written


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Regenerate project tracking files")
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args(argv)
    for path in build(args.root):
        print(f"updated {path.relative_to(args.root)}")


if __name__ == "__main__":
    main()
